#!/usr/bin/env node
/**
 * Regenerates the bundled copy of the shared promotional schedule.
 *
 * `packages/provider/promotions.json` is the only place windows are edited.
 * The generated module is what tsc and esbuild carry into both published
 * packages, so neither has to locate a JSON file on disk at runtime — which a
 * bundled CLI cannot do reliably anyway.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const SOURCE_PATH = path.join(root, "packages", "provider", "promotions.json");
export const OUTPUT_PATH = path.join(
  root,
  "packages",
  "provider",
  "src",
  "promotions",
  "bundled.ts",
);

/**
 * `JSON.parse` keeps a `__proto__` key as an ordinary own property, but the same
 * key written into an object literal sets the prototype instead. A schedule
 * carrying one would mean one thing fetched and another bundled, so it is
 * rejected here, while the file is still editable.
 */
function assertPlainKeys(value, at) {
  if (!value || typeof value !== "object") return;
  for (const [key, nested] of Object.entries(value)) {
    if (key === "__proto__") throw new Error(`${at} must not contain a __proto__ key`);
    assertPlainKeys(nested, `${at}.${key}`);
  }
}

export function renderModule(document) {
  assertPlainKeys(document, "promotions.json");
  return `// Generated from packages/provider/promotions.json by
// scripts/generate-promotions.mjs. Edit the JSON and run
// \`npm run promotions:generate\`; do not edit this file.
//
// The document stays \`unknown\` on purpose: it is data from a file people edit
// by hand, so the runtime normalizer in promotions.ts is its only gate.
export const BUNDLED_PROMOTIONS: unknown = ${JSON.stringify(document, null, 2)};
`;
}

export async function readSourceDocument() {
  return JSON.parse(await fs.readFile(SOURCE_PATH, "utf8"));
}

async function main() {
  await fs.writeFile(OUTPUT_PATH, renderModule(await readSourceDocument()), "utf8");
  process.stdout.write(`wrote ${path.relative(root, OUTPUT_PATH)}\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
